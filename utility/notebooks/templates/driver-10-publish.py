# %% [markdown]
# ## Assemble Silver from the handoffs

# %%
from datetime import date, datetime, timezone
from uuid import uuid4

SETUP_NOTEBOOK = "setup-10-publish-silver"

cfg = GenerationConfig(
    store_type=STORE_TYPE,
    start_date=date.fromisoformat(START_DATE),
    end_date=date.fromisoformat(END_DATE),
    store_count=STORE_COUNT,
    seed=SEED,
    silver_db=SILVER_DB,
    gold_db=GOLD_DB,
    dictionary_root="/lakehouse/default/Files/setup/dictionaries",
)
dicts = load_dictionaries(cfg.resolved_dictionary_root, cfg.store_type)

# Size shuffles to the generated volume (Spark's default 200 partitions makes each
# billion-row full-demo shuffle task spill millions of rows); adaptive execution
# coalesces small shuffles back down. Output does not depend on partitioning.
spark.conf.set("spark.sql.adaptive.enabled", "true")
spark.conf.set("spark.sql.adaptive.coalescePartitions.enabled", "true")
spark.conf.set(
    "spark.sql.shuffle.partitions",
    str(shuffle_partitions_for(cfg, dicts.profile.basket_lambda)),
)
print(f"spark.sql.shuffle.partitions={spark.conf.get('spark.sql.shuffle.partitions')}")

# Dimensions are regenerated in memory in every notebook: generation is fully
# deterministic (same seed => identical dims), so this is cheaper than a
# catalog round-trip. Checkpoints live in the Lakehouse, not on executors, so
# autoscaling or a lost executor cannot drop rows a later step still needs
# (CHECKPOINT_RDD_BLOCK_ID_NOT_FOUND). Each notebook owns its folder, so
# concurrent notebooks never touch each other's files; clearing it first
# removes whatever a failed attempt left behind.
checkpoint_dir = f"Files/setup/_checkpoints/{SETUP_NOTEBOOK}"
delete_lakehouse_path(spark, checkpoint_dir)
store = HandoffStore(spark, cfg, lakehouse=LAKEHOUSE_NAME)
tables, prestaged = load_publication(spark, dicts, cfg, store, checkpoint_dir=checkpoint_dir)

# %% [markdown]
# ## Check cross-table invariants

# %%
# Checks read Delta handoffs, so evaluating them concurrently is safe and
# removes per-check job overhead; results keep declaration order.
report = run_invariants(spark, tables, max_workers=PUBLISH_INVARIANT_WORKERS)
print(f"invariant checks run: {len(report.checks)}")
for name, count in sorted(report.row_counts.items()):
    print(f"  {name:40s} {count:>12,} rows")
if not report.passed:
    for failure in report.failures:
        print(f"FAILED: {failure}")
    raise RuntimeError(f"invariant failures: {report.failures}")
print("all invariants passed")

# %% [markdown]
# ## Publish atomically, then drop the handoffs

# %%
attempt_ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
run_id = f"setup-{STORE_TYPE}-{SEED}-{attempt_ts}-{uuid4().hex[:8]}"
# Gold is built in setup-11 from the persisted tables — pass an empty dict.
written = write_all(
    tables, {}, cfg, run_id, lakehouse=LAKEHOUSE_NAME, prestaged=prestaged,
)
print(f"wrote {len(written)} tables to {LAKEHOUSE_NAME}.{SILVER_DB} (run_id={run_id})")
# Silver now holds the data. Handoffs (including leftovers from failed runs)
# and this notebook's checkpoints are no longer needed.
store.drop_all()
delete_lakehouse_path(spark, checkpoint_dir)
